import fs from 'node:fs/promises'

import { DEPENDENCIES_MAP } from '../src/cli/constants'

const rootPkgUrl = new URL('../../../package.json', import.meta.url)
const pkgUrl = new URL('../package.json', import.meta.url)
const targetUrl = new URL('../src/cli/constants.generated.ts', import.meta.url)

const rootPkg = JSON.parse(await fs.readFile(rootPkgUrl, 'utf-8'))
const pkg = JSON.parse(await fs.readFile(pkgUrl, 'utf-8'))
const peerCatalog: Record<string, string> = rootPkg.workspaces?.catalogs?.peer ?? {}

const names = new Set([
  'oxfmt',
  'oxlint',
  ...Object.values(DEPENDENCIES_MAP).flat(),
  ...Object.keys(peerCatalog),
])

const versions: Record<string, string> = {
  [pkg.name]: `^${pkg.version}`,
}

for (const name of names) {
  if (peerCatalog[name]) {
    versions[name] = peerCatalog[name]
  }
}

const sortedVersions = Object.fromEntries(
  Object.entries(versions).sort(([a], [b]) => a.localeCompare(b)),
)

const banner = '// Generated by scripts/versiongen.ts - do not edit directly\n'
const content = `${banner}export const VERSIONS_MAP = ${JSON.stringify(sortedVersions, null, 2)} as const\n`

await fs.writeFile(targetUrl, content, 'utf-8')
